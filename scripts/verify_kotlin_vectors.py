#!/usr/bin/env python3
"""
scripts/verify_kotlin_vectors.py

Cross-language cryptographic parity verification (SEC-17, T1.7).
Reads vectors generated by Kotlin (app/build/kotlin_vectors.json)
and independently verifies every frame using Python pycryptodome.
"""

import json
import struct
import sys
from pathlib import Path

from Crypto.Cipher import AES
from Crypto.Hash import SHA256
from Crypto.PublicKey import ECC
from Crypto.Signature import DSS

# Add scripts directory to path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import wire_spec


KOTLIN_VECTORS_PATH = (
    Path(__file__).resolve().parent.parent / "app" / "build" / "kotlin_vectors.json"
)


def compute_sender_fp(uncompressed_pubkey: bytes) -> int:
    digest = SHA256.new(uncompressed_pubkey).digest()
    return struct.unpack(">Q", digest[:8])[0]


def verify_vector(idx: int, vec: dict) -> None:
    # 1. Parse hex fields
    pub_bytes = bytes.fromhex(vec["signing_pubkey_uncompressed_hex"])
    assert len(pub_bytes) == 65 and pub_bytes[0] == 0x04, f"Vector {idx}: Invalid EC public key"

    # Verify fingerprint derivation
    expected_fp = int(vec["sender_fp_hex"], 16)
    computed_fp = compute_sender_fp(pub_bytes)
    assert computed_fp == expected_fp, f"Vector {idx}: Fingerprint mismatch! Expected {expected_fp:016x}, got {computed_fp:016x}"

    # 2. Verify AAD calculation
    packet_type = vec["packet_type"]
    ttl = vec["ttl"]
    msg_id = int(vec["msg_id_hex"], 16)
    group_id = int(vec["group_id_hex"], 16)
    key_epoch = vec["key_epoch"]

    expected_aad = struct.pack(">BQIQH", packet_type, msg_id, group_id, computed_fp, key_epoch)
    actual_aad = bytes.fromhex(vec["aad_hex"])
    assert actual_aad == expected_aad, f"Vector {idx}: AAD mismatch"

    # 3. Verify frame structure
    frame = bytes.fromhex(vec["frame_hex"])
    assert len(frame) == vec["frame_len"], f"Vector {idx}: Frame length mismatch"

    header_bytes = frame[:24]
    expected_header = struct.pack(">BBQIQH", packet_type, ttl, msg_id, group_id, computed_fp, key_epoch)
    assert header_bytes == expected_header, f"Vector {idx}: Header bytes mismatch"

    sig_bytes = frame[-64:]
    assert sig_bytes == bytes.fromhex(vec["signature_hex"]), f"Vector {idx}: Signature bytes mismatch"

    core_blob = frame[24:-64]
    nonce = core_blob[:12]
    tag = core_blob[12:28]
    ct_len = struct.unpack(">I", core_blob[28:32])[0]
    ciphertext = core_blob[32:]
    assert len(ciphertext) == ct_len, f"Vector {idx}: Ciphertext length mismatch"

    assert nonce == bytes.fromhex(vec["nonce_hex"]), f"Vector {idx}: Nonce mismatch"
    assert tag == bytes.fromhex(vec["tag_hex"]), f"Vector {idx}: Tag mismatch"
    assert ciphertext == bytes.fromhex(vec["ciphertext_hex"]), f"Vector {idx}: Ciphertext mismatch"

    # 4. Verify ECDSA signature over (AAD || CoreBlob)
    signed_data = actual_aad + core_blob
    hasher = SHA256.new(signed_data)

    # Reconstruct ECC public key from 65-byte uncompressed format (0x04 || X || Y)
    x_int = int.from_bytes(pub_bytes[1:33], "big")
    y_int = int.from_bytes(pub_bytes[33:65], "big")
    ecc_pubkey = ECC.construct(curve="p256", point_x=x_int, point_y=y_int)

    verifier = DSS.new(ecc_pubkey, mode="fips-186-3", encoding="binary")
    try:
        verifier.verify(hasher, sig_bytes)
    except ValueError as e:
        raise AssertionError(f"Vector {idx}: ECDSA signature verification failed: {e}")

    # 5. Open AES-256-GCM ciphertext
    group_key = bytes.fromhex(vec["group_key_hex"])
    cipher = AES.new(group_key, AES.MODE_GCM, nonce=nonce)
    cipher.update(actual_aad)
    try:
        decrypted_payload = cipher.decrypt_and_verify(ciphertext, tag)
    except ValueError as e:
        raise AssertionError(f"Vector {idx}: AES-GCM decryption failed: {e}")

    # 6. Verify inner payload: sent_at (8B BE int64) + plaintext
    assert len(decrypted_payload) >= 8, f"Vector {idx}: Decrypted inner payload too short"
    sent_at_ms = struct.unpack(">q", decrypted_payload[:8])[0]
    plaintext = decrypted_payload[8:].decode("utf-8")

    assert sent_at_ms == vec["sent_at_ms"], f"Vector {idx}: sent_at_ms mismatch"
    assert plaintext == vec["plaintext"], f"Vector {idx}: Plaintext mismatch"


def main() -> int:
    print("[verify_kotlin_vectors] Verifying Kotlin-generated crypto vectors in Python...")

    if not KOTLIN_VECTORS_PATH.is_file():
        print(f"[verify_kotlin_vectors] ERROR: {KOTLIN_VECTORS_PATH} not found. Run unit tests first.", file=sys.stderr)
        return 1

    data = json.loads(KOTLIN_VECTORS_PATH.read_text(encoding="utf-8"))
    vectors = data.get("vectors", [])
    print(f"[verify_kotlin_vectors] Loaded {len(vectors)} vectors from {KOTLIN_VECTORS_PATH.name}")

    if len(vectors) < 20:
        print(f"[verify_kotlin_vectors] ERROR: Expected at least 20 vectors, found {len(vectors)}", file=sys.stderr)
        return 1

    for idx, vec in enumerate(vectors):
        try:
            verify_vector(idx, vec)
        except Exception as e:
            print(f"[verify_kotlin_vectors] FAILED on vector {idx} ({vec.get('description', '')}): {e}", file=sys.stderr)
            return 1

    print(f"[verify_kotlin_vectors] SUCCESS: All {len(vectors)} Kotlin vectors verified 100% in Python!")
    return 0


if __name__ == "__main__":
    sys.exit(main())
